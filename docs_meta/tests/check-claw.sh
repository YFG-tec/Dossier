#!/usr/bin/env bash
# 第 4 条推广验收：结案、发授权、松判据，都是人的那一爪。
# 零权威，只作证，不算「通过」。用法：bash docs_meta/tests/check-claw.sh
#
# **扫描范围**：paradigm.md §3 里 `4. ` 开头那一条 + 其后的缩进续行。
# 顶格的非条目行终结这一条（第 5 条、散文段落都不并进来），形状抄 check-done.sh 的 rows()。
#
# 口径（脚本和文档必须同一套）：
#
#   A 推广落到位 —— 这一条须同时出现「结案」「发授权」「松判据」。
#     三样是人 2026-09-08 分两次拍的：前两样在 cmd/PROMPT_1.3.md 闸二，
#     第三样在 cmd/PROMPT_1.4.md 返工第 4 条。缺一样就是推广没做完。
#
#   B 原句没被抽象掉 —— 这一条须仍出现「勾」和「TODO」。
#     旧条文是「代理不准自己勾 TODO」。上位句写好了，具体禁令就容易被当成冗余删掉——
#     **具体实例是抽象条文唯一的锚**（§10 自己写的：不带理由的规矩，下一个人会当成税删掉）。
#     抽象句吃掉具体禁令，就是 §3 自己点名的那种静默降档：没有任何东西会变红。
#     **所以这一条是防退化的，它开工前本来就是绿的**——红证必须现做，不许拿「从来没红过」交差。
#
#   C 方向差没丢 —— 这一条须出现「收紧」。
#     「松判据」只指放宽一个方向：放宽验收命令、改宽检查口径、接受偏离合同的折衷。
#     **收紧是测试那只手的本职**——check-mark.sh C4 和 check-link.sh B 的脚本头都已经这么写了。
#     条文若不写清方向，下一个人会读成「判据一律不许动」，**当场把 contract-tester 这只手废掉**。
#     这一条查的是「方向差在不在」，查不了「方向有没有写反」——那要人眼。
#
#   D 指路不复述 —— 这一条须出现「§5」指针，且**不许**出现「标出处」。
#     人的决定存在于发言里，没有可指的东西，做不成链接，所以代落的记录落 §5 末段**第二档**。
#     第 4 条指过去就够；把第二档的要求再写一遍，就是第二份内容——正是第二档自己禁止的事。
#     **这是库里第一条负向检查**（要求某个词不出现），而本刀自己是第一个被它管的。
#
#   **四条都扫原文，不剥围栏。** 上一刀那条「裸的是授权、围栏里的是提及」是为标记立的；
#   这里问的是「条文里写没写这几个词」，反引号里的也是写了。
#   判据要跟着问题走，不跟着上一条判据走。
#
# **已知缺口，照记不照补：**
#   - **不查 §3 加没加标记**：check-mark.sh B 已经管了（裸标记只许 §5 / §6 / §10）。
#     重复造就是第二份检查。
#   - **不查有没有写成例外**（「不在此列」/「除…之外」/「唯一例外」/「不适用」）。
#     这四个是精确子串，机器本来做得了——**但卡片只点了四条，加第五条是收紧判据，
#     而收紧是测试那只手的本职，不是实现顺手加的。** 这一刀由审查用人眼看（独立审查第 3 条）。
#     缺口留在这里，别当它已经查了。
#
# 这四条拦得住「推广漏了一样」「原句被抽掉」「方向差没了」「第二档被复述」，
# **拦不住「三个实例各自解释错了」**——那要人眼。
# 能机检的是词的共现，不是意思（paradigm.md §6 那条【定】自己写的）。照写，不吹。
cd "$(dirname "$0")/../.."
fail=0
PARA=docs_meta/docs/design/paradigm.md

[ -f "$PARA" ] || { echo "FAIL: $PARA 不存在"; exit 1; }

# 取 §3 里第 4 条的全文（条目行 + 缩进续行）。输出：起始行号 <TAB> 全文
item4() {
  awk '
    /^## /      { insec = ($0 ~ /^## 3 /); if (!insec && buf!="") exit; next }
    !insec      { next }
    /^4\. /     { n=NR; buf=$0; on=1; next }
    on && /^[[:space:]]+[^[:space:]]/ { buf = buf " " $0; next }
    on && /^[[:space:]]*$/            { next }
    on          { exit }
    END         { if (buf!="") print n "\t" buf }
  ' "$PARA"
}

row=$(item4)
no=${row%%$'\t'*}
txt=${row#*$'\t'}

echo "== 范围：paradigm.md §3 第 4 条 =="
if [ -z "$row" ]; then
  echo "   FAIL: §3 里找不到「4. 」开头的条目——七条不变量少了一条"
  echo
  echo "FAILED"
  exit 1
fi
echo "   第 $no 行起，共 $(printf '%s' "$txt" | wc -c) 字节"
printf '   %s\n' "$txt"

echo
echo "== A 推广落到位：须同时出现「结案」「发授权」「松判据」 =="
for kw in $'结案' $'发授权' $'松判据'; do
  if printf '%s' "$txt" | grep -q "$kw"; then
    echo "   「$kw」  OK"
  else
    echo "   「$kw」  FAIL: 没出现——推广没做完"
    fail=1
  fi
done

echo
echo "== B 原句没被抽象掉：须仍出现「勾」和「TODO」 =="
echo "   （防退化。抽象句吃掉具体禁令 = 静默降档，没有任何东西会变红）"
for kw in $'勾' 'TODO'; do
  if printf '%s' "$txt" | grep -q "$kw"; then
    echo "   「$kw」  OK"
  else
    echo "   「$kw」  FAIL: 原句「代理不准自己勾 TODO」被抽掉了"
    fail=1
  fi
done

echo
echo "== C 方向差没丢：须出现「收紧」 =="
echo "   （松判据只指放宽一个方向；收紧是测试那只手的本职）"
if printf '%s' "$txt" | grep -q $'收紧'; then
  echo "   「收紧」  OK"
else
  echo "   「收紧」  FAIL: 方向没写清——下一个人会读成「判据一律不许动」，废掉 contract-tester"
  fail=1
fi

echo
echo "== D 指路不复述：须有「§5」指针，且不许出现「标出处」 =="
if printf '%s' "$txt" | grep -q '§5'; then
  echo "   「§5」  OK: 指过去了"
else
  echo "   「§5」  FAIL: 没有指针——代落的记录怎么写，无处可查"
  fail=1
fi
if printf '%s' "$txt" | grep -q $'标出处'; then
  echo "   「标出处」  FAIL: 复述了第二档的要求——指过去就够，写第二遍就是第二份内容"
  fail=1
else
  echo "   「标出处」  OK: 没复述"
fi

echo
if [ "$fail" -eq 0 ]; then echo "ALL PASS"; else echo "FAILED"; fi
exit $fail
