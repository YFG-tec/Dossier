#!/usr/bin/env bash
# 席 / 手两根轴的绊线。零权威，只作证，不算「通过」。
# 用法：bash docs_meta/tests/check-seat.sh
#
# 谁加的：2026-09-10 由 cmd/PROMPT_009.md 新增，实现席这只手写的。
# **这是收紧，不是放宽**，所以不另发一次授权（paradigm.md §3 第 4 条：松判据才是人的那一爪）。
# 同 check-link.sh C / D 两段那条理由。
#
# 钉的是哪一裁：**档位拧的是领班以下那几只手，不拧席。**
#   席常设两个、两个会话；手按「有没有编译运行」多分或少分。
#   卡本体由一只手执笔、另一席 review、两边共识才推进；**哪一席执笔由桌自己定**。
#
# 口径（脚本和文档必须同一套）：
#
#   A 判据在 —— `## 档位` 那一节必须出现「编译运行」。
#     判据是结构条件，不是阶段论。有人把理由改回「现在还早」「等成熟了再说」，词一没就红。
#
#   B 席没被拧动 —— 必须仍有「两席必须是两个会话」这一句。
#     第二版就是想放松它，被人当场推翻。有人再把档位拧到席上，当场红。
#
#   C 共识条款在 —— `## 两席` 那一节必须出现「共识」二字。
#     共识是推进条件，不是可选的礼节。被删掉，当场红。
#
#   D 母本的填法没漏进通则 —— 凡含「卡本体」的行，同行必须含「由桌」或「各桌」。
#     `src/` 是通则源码，效果转译进每一张桌。「卡本体归领班」是母本填的那一格，
#     该落 docs/design/paradigm.md §5；通则这一头只许写「由桌自己定」。
#     填死了当场红。
#
#   E 表格没被改回填死 —— `## 两席` 那一节里，**以 `|` 开头的表格行**凡含「写卡」，同行必须含「由桌」。
#     卡第六版就是栽在这里：正文按分层松开了，同一节那张表两格没跟上，
#     规划席「干什么」仍写着「写卡」。靠 D 那一条抓不到——表格行里没有「卡本体」四个字。
#
#     **射程只到表格行，这是本刀自己收的，照写不吹。** 卡上第五条写的是「那一节里凡出现
#     『写卡』二字的行」。照字面实现，这条绊线一出生就红：同一节现成有一句
#     「开桌那一段是规划席唯一一次**不写卡**的正事」，它含「写卡」而不该含「由桌」。
#     要救它就得去改那一句，而那一句不在本刀「交什么」的许可里——
#     于是字面口径和 `## 两席` 那一件的射程互相打架。取表格行，两边就一致了。
#     形状照 check-link.sh 那条「只扫横线以上」的射程写：**断言本身一个字没松，收的是射程。**
#     **这是本刀这只手的判断，不是人裁的。** 闸二若认为该照字面，改回来即可，另五条不受影响。
#
#   F 已于 2026-09-10 退役，依 cmd/PROMPT_012.md（todo.md 2.5，人落槌「直接退役」）。
#     原来守什么：仓库里不许出现 docs_meta/tests/ 或根 test/ 的**文件**。
#     判据是「有没有编译运行」——母本长出能机械变红的东西，档位表那条前提就没了。
#     为什么退：它是一次性绊线。2.5 把八本检查搬进 docs_meta/tests/，
#     落成的正是它守的那个翻转点；响过一次就再没有信息量，也不会自己转绿。
#
#     **代价照写，不粉饰：** 退掉 F 之后，**母本没有任何机械物盯着档位那条前提**，
#     roles.md 那根轴此后只靠文字拦。同 check-mark.sh B 退役时「只靠文首一行字拦」那个形状。
#
#     **退的是哨兵，不是判据。** 人裁的是「F 退役」，没裁「翻转到底发没发生」——
#     那一问归 2.6，本脚本不替它答。F 头注释原来兼的那笔账已整本搬进
#     design/paradigm.md §9「改核的手同时动判据」那一行，这里一个字不留：留副本就是第二真相。
#
#     文件名不改：A–E 五段仍管席和手两根轴，check-seat 这个名字仍然准。
#
# **不设放行词。** 五条一条都没留「同一行还出现某某就放过」的口子。
#   留了就等于说「提一句可以」，而「提一句」和「真填死」之间没有机器分得清的界（同 check-link.sh A）。
#
# **它查不了什么，照写不吹：** 查得了词在不在、哪几个词有没有落在同一行，
#   **查不了整段读下来是不是仍然说反了**（paradigm.md §6：能机检的是词的共现，不是意思）。
#   五条全绿，正文照样可以把档位重新拧回席上——只要它绕开这几个词。
#   拦得住手滑，拦不住误解。
cd "$(dirname "$0")/../.."
fail=0
R=docs_meta/src/roles.md

[ -f "$R" ] || { echo "FAIL: $R 不存在"; exit 1; }

# 取节：从 ^## <名> 到下一个 ^## 之前。带原文行号，报告时能点名。
section() {
  awk -v pat="$1" '
    $0 ~ "^## " pat { f=1; print NR"\t"$0; next }
    /^## / { f=0 }
    f { print NR"\t"$0 }
  ' "$R"
}

TWO=$(section '两席')
GEAR=$(section '档位')

[ -n "$TWO" ]  || { echo "FAIL: $R 里找不到 '## 两席' 那一节"; exit 1; }
[ -n "$GEAR" ] || { echo "FAIL: $R 里找不到 '## 档位' 那一节"; exit 1; }

echo "（射程：roles.md；两席节 $(printf '%s\n' "$TWO" | wc -l) 行，档位节 $(printf '%s\n' "$GEAR" | wc -l) 行）"
echo

echo "== A 判据在：'## 档位' 那一节必须出现「编译运行」 =="
echo "   （判据是结构条件；理由退回阶段论，词一没就红）"
hit=$(printf '%s\n' "$GEAR" | grep '编译运行')
if [ -n "$hit" ]; then
  printf '   %s\n' "$hit"
  echo "   PASS: 判据词在"
else
  echo "   FAIL: 档位那一节没有「编译运行」——判据不在，或者被改回了阶段论"
  fail=1
fi

echo
echo "== B 席没被拧动：必须仍有「两席必须是两个会话」 =="
echo "   （档位拧的是领班以下那几只手，不拧席）"
hit=$(grep -n '两席必须是两个会话' "$R")
if [ -n "$hit" ]; then
  printf '   %s\n' "$hit"
  echo "   PASS: 那一句在"
else
  echo "   FAIL: 「两席必须是两个会话」不见了——有人把档位拧到席上了"
  fail=1
fi

echo
echo "== C 共识条款在：'## 两席' 那一节必须出现「共识」 =="
echo "   （共识是推进条件，不是可选的礼节）"
hit=$(printf '%s\n' "$TWO" | grep '共识')
if [ -n "$hit" ]; then
  printf '   %s\n' "$hit"
  echo "   PASS: 共识在"
else
  echo "   FAIL: 两席那一节没有「共识」——推进条件被删了"
  fail=1
fi

echo
echo "== D 母本的填法没漏进通则：凡含「卡本体」的行，同行必须含「由桌」或「各桌」 =="
echo "   （src/ 是通则源码，效果进每一张桌；母本填的那一格落 docs/design/paradigm.md §5）"
lines=$(grep -n '卡本体' "$R")
if [ -z "$lines" ]; then
  echo "   FAIL: 整份 roles.md 没有「卡本体」——那一段共识条款不在"
  fail=1
else
  d=0
  while IFS= read -r l; do
    if printf '%s' "$l" | grep -q '由桌\|各桌'; then
      printf '   OK   %s\n' "$l"
    else
      printf '   BAD  %s\n' "$l"
      d=1
    fi
  done <<< "$lines"
  if [ "$d" -eq 0 ]; then
    echo "   PASS: 每一处「卡本体」都留着「由桌 / 各桌」那一格"
  else
    echo "   FAIL: 上面 BAD 那几行把执笔的席填死在通则里了"
    fail=1
  fi
fi

echo
echo "== E 表格没被改回填死：'## 两席' 的表格行凡含「写卡」，同行必须含「由桌」 =="
echo "   （射程只到以 | 开头的表格行，理由见脚本头——本刀自己收的射程，不是人裁的）"
rows=$(printf '%s\n' "$TWO" | awk -F'\t' '$2 ~ /^\|/' | grep '写卡')
if [ -z "$rows" ]; then
  echo "   （表格行里没有「写卡」——这一条无从查起，不算红）"
  echo "   PASS: 没有可填死的格"
else
  e=0
  while IFS= read -r l; do
    if printf '%s' "$l" | grep -q '由桌'; then
      printf '   OK   %s\n' "$l"
    else
      printf '   BAD  %s\n' "$l"
      e=1
    fi
  done <<< "$rows"
  if [ "$e" -eq 0 ]; then
    echo "   PASS: 表格两格和正文同一套口径"
  else
    echo "   FAIL: 正文说「由桌定」、表格说规划席写卡——同一节自打"
    fail=1
  fi
fi

echo
if [ "$fail" -eq 0 ]; then echo "ALL PASS"; else echo "FAILED"; fi
exit $fail
