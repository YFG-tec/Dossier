#!/usr/bin/env bash
# 「谁决定什么」验收：结案、发授权、松判据，都是人的那一爪。
# 零权威，只作证，不算「通过」。用法：bash docs_meta/tests/check-paw.sh
#
# **本刀改过名**（人 2026-09-11 落槌）。旧名 `check-claw`。
# 理由：claw 在英文里多指钳子，和 openclaw 语义撞；这套里那一下不是夹东西，
# 是猫爪盖章——「爪」和「印」本来就是同一个动作。**代价照写，不粉饰**：
# 已结案的三张卡（`cmd/PROMPT_005` / `011` / `012`）里还写着旧名，记录层只追加，不改。
# 所以从第四刀起，若要按名字全仓 grep 这本检查，会同时漏掉那三处历史记录。
#
# **2026-09-11 换了断言对象**（`cmd/PROMPT_013.md` 第 13 件）。
# 原来扫 `paradigm.md` §3 第 4 条。那一刀把 `design/` 从红绿判定里剥出去，
# 拿一份思路层的条目当断言对象，正是那一刀要废掉的用法。
# 现在 A / B 扫 `roles.md`「谁决定什么」那一节，C 扫 `directory.md`。
# `paradigm.md` §3 那一段留在原地不动，本刀只是不再断言它。
#
# **扫描范围从「按条抽」改成「按节抽」**：`roles.md` 里没有 `paradigm.md` 那种编号条目，
# 照搬原来的 `item4()` 没有对象。人 2026-09-11 裁：「先保证跑通，按节进行编排」。
# **代价照写**：范围变宽了。节里多写的话也算数，A / B 会比原来更容易绿。
# 节一改名、一合并、内容一挪，抽取范围跟着变——**不是变红，是变松，而且不会有东西告诉你**。
#
# 口径（脚本和文档必须同一套）：
#
#   A 三样齐全 —— 那一节须同时出现「结案」「发授权」「松判据」。
#     三样是人 2026-09-08 分两次拍的：前两样在 cmd/PROMPT_1.3.md，
#     第三样在 cmd/PROMPT_1.4.md 返工第 4 条。缺一样就是这条不变量没写完。
#
#   B 原句没被抽象掉 —— 那一节须仍出现「勾」和「TODO」。
#     旧条文是「代理不准自己勾 TODO」。上位句写好了，具体禁令就容易被当成冗余删掉——
#     **具体实例是抽象条文唯一的锚**。抽象句吃掉具体禁令是静默降档：没有任何东西会变红。
#     **所以这一条是防退化的，它开工前本来就是绿的**——红证必须现做，不许拿「从来没红过」交差。
#
#   C 方向差没丢 —— `directory.md` 里须有一行同时出现「收紧」和「本职」。
#     锚的是「`tests/` 不上这张表」那一段：跟卡写红测、收紧，是测试席本职；
#     放宽口径是人的那一爪。「松判据」只指放宽一个方向。
#     条文若不写清方向，下一个人会读成「判据一律不许动」，**当场把 contract-tester 这只手废掉**。
#     这一条查的是「方向差在不在」，查不了「方向有没有写反」——那要人眼。
#
#   D 退役（2026-09-11，人落槌「删了就行」）。原来查的是：§3 第 4 条须有「§5」指针、
#     且不许出现「标出处」——两半都以 `paradigm.md` §5 为对象。断言对象一换，那个 `§5`
#     是 `paradigm.md` 自己的章节号，指针整个没有对象。**D 是随对象一起消失的，不是本刀砍的。**
#
#     **代价照写，说准**：代落的规格本来就在 `roles.md`（照抄、标出处、不摘要、不合并、不改措辞），
#     从来没在 `paradigm.md` 里，所以**没有功能搬走，也没有降成散文**。
#     D 断言的其实是「那一条有没有把指针指出去、有没有顺手把下游复述一遍」。
#     这一格现在空着：新节里那句指针没有哨兵盯着它写没写、指没指对。
#     **是少了一格，不是换了地方。**
#
#   **三条都扫原文，不剥围栏。** 上一刀那条「裸的是授权、围栏里的是提及」是为标记立的；
#   这里问的是「条文里写没写这几个词」，反引号里的也是写了。
#   判据要跟着问题走，不跟着上一条判据走。
#
# **已知缺口，照记不照补：**
#   - **不查有没有写成例外**（「不在此列」/「除…之外」/「唯一例外」/「不适用」）。
#     这四个是精确子串，机器本来做得了——**但卡片只点了这几条，加一条是收紧判据，
#     而收紧是测试那只手的本职，不是实现顺手加的。** 由审查用人眼看。
#     缺口留在这里，别当它已经查了。
#
# 这三条拦得住「三样漏了一样」「原句被抽掉」「方向差没了」，
# **拦不住「三个实例各自解释错了」**——那要人眼。
# 能机检的是词的共现，不是意思。照写，不吹。
cd "$(dirname "$0")/../.."
fail=0
ROLES=docs_meta/src/roles.md
DIR=docs_meta/src/directory.md

[ -f "$ROLES" ] || { echo "FAIL: $ROLES 不存在"; exit 1; }
[ -f "$DIR" ]   || { echo "FAIL: $DIR 不存在"; exit 1; }

# 取 roles.md「谁决定什么」整节（标题行之后到下一个 ## 之前）。输出：起始行号 <TAB> 全文
section() {
  awk '
    /^## / { if (on) exit; if ($0 ~ /^## 谁决定什么/) { n=NR; on=1 } next }
    on     { buf = buf " " $0 }
    END    { if (on) print n "\t" buf }
  ' "$ROLES"
}

row=$(section)
no=${row%%$'\t'*}
txt=${row#*$'\t'}

echo "== 范围：roles.md「谁决定什么」整节（按节抽，不是按条抽） =="
if [ -z "$row" ]; then
  echo "   FAIL: roles.md 里找不到「## 谁决定什么」这一节——决定权那条不变量没了落点"
  echo
  echo "FAILED"
  exit 1
fi
echo "   第 $no 行起，共 $(printf '%s' "$txt" | wc -c) 字节"

echo
echo "== A 三样齐全：须同时出现「结案」「发授权」「松判据」 =="
for kw in $'结案' $'发授权' $'松判据'; do
  if printf '%s' "$txt" | grep -q "$kw"; then
    echo "   「$kw」  OK"
  else
    echo "   「$kw」  FAIL: 没出现——三样缺一样"
    fail=1
  fi
done

echo
echo "== B 原句没被抽象掉：须仍出现「勾」和「TODO」 =="
echo "   （防退化。抽象句吃掉具体禁令 = 静默降档，没有任何东西会变红）"
for kw in $'勾' 'TODO'; do
  if printf '%s' "$txt" | grep -q "$kw"; then
    echo "   「$kw」  OK"
  else
    echo "   「$kw」  FAIL: 原句「代理不准自己勾 TODO」被抽掉了"
    fail=1
  fi
done

echo
echo "== C 方向差没丢：directory.md 里须有一行同时写着「收紧」和「本职」 =="
echo "   （松判据只指放宽一个方向；收紧是测试那只手的本职）"
hit=$(grep -n $'收紧' "$DIR" | grep $'本职')
if [ -n "$hit" ]; then
  printf '   %s\n' "$hit"
  echo "   PASS: 方向差在"
else
  echo "   FAIL: 方向没写清——下一个人会读成「判据一律不许动」，废掉 contract-tester"
  fail=1
fi

echo
echo "== D 已退役（2026-09-11）：原来查 §3 第 4 条的「§5」指针和「标出处」 =="
echo "   （断言对象换了，那个指针没有对象。代价见脚本头：是少了一格，不是换了地方）"

echo
if [ "$fail" -eq 0 ]; then echo "ALL PASS"; else echo "FAILED"; fi
exit $fail
